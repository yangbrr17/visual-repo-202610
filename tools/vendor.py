#!/usr/bin/env python3
"""Fetch pinned third-party front-end builds from npm into vendor/.

Every package is declared in vendor/vendor.json (name, npm spec, license,
upstream repo, and which files of the published tarball we keep). Running
this script is reproducible: same manifest -> same files.

    python3 tools/vendor.py            # fetch everything
    python3 tools/vendor.py echarts    # fetch one id
    python3 tools/vendor.py --check    # verify files exist, no network
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor"
MANIFEST = VENDOR / "vendor.json"


def load_manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def fetch(pkg: dict, work: Path) -> None:
    spec = f"{pkg['npm']}@{pkg['version']}"
    out = subprocess.run(
        ["npm", "pack", spec, "--silent", "--pack-destination", str(work)],
        check=True, capture_output=True, text=True,
    ).stdout.strip().splitlines()[-1]
    tgz = work / out
    extract = work / f"x-{pkg['id']}"
    extract.mkdir()
    with tarfile.open(tgz) as tf:
        tf.extractall(extract, filter="data")
    src_root = extract / "package"
    dest = ROOT / pkg["dest"] if pkg.get("dest") else VENDOR / pkg["id"]
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    for src_rel, dst_rel in pkg["files"].items():
        matches = sorted(src_root.glob(src_rel)) if any(c in src_rel for c in "*?[") else [src_root / src_rel]
        if not matches or not matches[0].exists():
            raise SystemExit(f"[{pkg['id']}] missing file in tarball: {src_rel}")
        for m in matches:
            if m.is_dir():
                target = dest / dst_rel.rstrip("/")
            elif dst_rel.endswith("/"):
                target = dest / dst_rel / m.name
            else:
                target = dest / dst_rel
            target.parent.mkdir(parents=True, exist_ok=True)
            if m.is_dir():
                shutil.copytree(m, target, dirs_exist_ok=True)
            else:
                shutil.copy2(m, target)
    print(f"  ok  {pkg['id']:<22} {spec}")


def write_licenses(manifest: dict) -> None:
    lines = [
        "# Third-party components",
        "",
        "Generated by `tools/vendor.py` from `vendor/vendor.json`. Each folder keeps the",
        "upstream LICENSE/NOTICE file next to the distributed build.",
        "",
        "| id | package | version | license | upstream | used for |",
        "|---|---|---|---|---|---|",
    ]
    for p in manifest["packages"]:
        lines.append(
            f"| `{p['id']}` | `{p['npm']}` | {p['version']} | {p['license']} | {p['repo']} | {p.get('purpose', '')} |"
        )
    (VENDOR / "LICENSES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def check(manifest: dict) -> int:
    bad = 0
    for p in manifest["packages"]:
        for dst_rel in p["files"].values():
            if dst_rel.endswith("/"):
                continue
            base = ROOT / p["dest"] if p.get("dest") else VENDOR / p["id"]
            if not (base / dst_rel).exists():
                print(f"missing: {base.relative_to(ROOT)}/{dst_rel}")
                bad += 1
    print("vendor check:", "OK" if not bad else f"{bad} missing")
    return 1 if bad else 0


def main(argv: list[str]) -> int:
    manifest = load_manifest()
    if "--check" in argv:
        return check(manifest)
    only = {a for a in argv if not a.startswith("-")}
    with tempfile.TemporaryDirectory() as tmp:
        for pkg in manifest["packages"]:
            if only and pkg["id"] not in only:
                continue
            if pkg.get("local"):
                continue  # generated in-repo (see tools/build_geo.py)
            fetch(pkg, Path(tmp))
    write_licenses(manifest)
    return check(manifest)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
