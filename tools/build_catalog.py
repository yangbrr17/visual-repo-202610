#!/usr/bin/env python3
"""Build the component catalog from manifests (single source of truth).

    python3 tools/build_catalog.py

Reads   kit/components/*/manifest.json, kit/categories.json, kit/build.json, vendor/vendor.json,
        kit/samples/datasets/*.json, research/catalog.json (optional),
        gallery/thumbs/thumbs.json (optional, written by node tools/thumbs.cjs)
Writes  kit/catalog.json            consolidated manifests (used by Python / docs)
        gallery/catalog.js          window.RK_GALLERY = {...}   (classic script: works from file://)
        gallery/samples.js          window.RK_GALLERY_DATA = {...}
        docs/component-catalog.md   generated catalogue table

Also lints every manifest sample against its own manifest (unknown option / encode channel names,
encode fields missing from the sample datasets) so the gallery's usage snippets stay current.
`--strict` exits 1 on any warning.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "kit"


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8"))


def js_assign(name: str, obj) -> str:
    body = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    return f"/* generated by tools/build_catalog.py — do not edit */\nwindow.{name} = {body};\n"


# options every block understands (handled by the runtime, not by the component; docs/architecture.md §6-7)
GENERIC_OPTIONS = {"encode", "tools", "where", "filters", "ignoreFilters", "crossFilterScope",
                   "choices", "choiceLabels", "selectionFallback", "badges", "printFit"}


def lint_samples(m: dict, datasets: dict) -> list[str]:
    """Problems in a manifest's samples: option / channel names not in the manifest, unknown fields."""
    out = []
    known = set(m.get("options") or {}) | GENERIC_OPTIONS
    channels = set(m.get("channels") or {})
    for i, smp in enumerate(m.get("samples") or []):
        where = f"{m['id']} sample {i + 1} ({smp.get('title', '')[:40]!r})"
        opts = smp.get("options") or {}
        for k in opts:
            if k not in known:
                out.append(f"{where}: option '{k}' is not in the manifest options")
        enc = opts.get("encode") or {}
        bound = [smp["data"]] if smp.get("data") else []
        bound += [v for k, v in opts.items() if k.endswith("Data") and isinstance(v, str)]
        fields = set()
        for d in bound:
            fields |= {f["name"] for f in (datasets.get(d) or {}).get("schema", {}).get("fields", [])}
        for ch, val in enc.items():
            if channels and ch not in channels:
                out.append(f"{where}: encode channel '{ch}' is not in the manifest channels")
            refs = [val] if isinstance(val, str) else [v for v in val if isinstance(v, str)] if isinstance(val, list) else []
            for ref in refs:
                if fields and ref not in fields:
                    out.append(f"{where}: encode.{ch} -> '{ref}' is not a field of {', '.join(bound)}")
    return out


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser(description="Build kit/catalog.json, gallery/catalog.js, gallery/samples.js and docs/component-catalog.md from component manifests.")
    ap.add_argument("--strict", action="store_true", help="exit 1 when any manifest / sample problem is found")
    args = ap.parse_args()
    cats = load(KIT / "categories.json")["categories"]
    cat_ids = [c["id"] for c in cats]
    build = load(KIT / "build.json")
    vendor = load(ROOT / "vendor" / "vendor.json")

    comps, problems = [], []
    for mf in sorted((KIT / "components").glob("*/manifest.json")):
        try:
            m = load(mf)
        except json.JSONDecodeError as e:
            problems.append(f"{mf}: invalid JSON ({e})")
            continue
        cid = mf.parent.name
        if m.get("id") != cid:
            problems.append(f"{mf}: id '{m.get('id')}' != folder '{cid}'")
        if m.get("category") not in cat_ids:
            problems.append(f"{cid}: unknown category '{m.get('category')}'")
        if not (mf.parent / f"{cid}.js").exists():
            problems.append(f"{cid}: missing {cid}.js")
        m["has_css"] = (mf.parent / f"{cid}.css").exists()
        comps.append(m)

    order = {c: i for i, c in enumerate(cat_ids)}
    comps.sort(key=lambda m: (order.get(m.get("category"), 99), m.get("name", m["id"])))

    # sample datasets referenced by manifests
    ds_dir = KIT / "samples" / "datasets"
    datasets = {}
    if ds_dir.exists():
        for f in sorted(ds_dir.glob("*.json")):
            datasets[f.stem] = load(f)
    used = set()
    for m in comps:
        for s in m.get("samples", []):
            if s.get("data"):
                used.add(s["data"])
            for k, v in (s.get("options") or {}).items():
                if k.endswith("Data") and isinstance(v, str):
                    used.add(v)
    missing = sorted(u for u in used if u not in datasets)
    for u in missing:
        problems.append(f"sample dataset '{u}' referenced by a manifest is missing in kit/samples/datasets/")
    for m in comps:
        problems += lint_samples(m, datasets)

    # vendor packages for the gallery. preload: some component lists it in "deps" (the gallery loads it up front);
    # onDemand: components that need it only for certain option values (manifest "optionDeps", e.g. basemap
    # "world-50m" -> geo-world-50m, 756 KB) — those components fetch it themselves when a block asks for it.
    dep_users, opt_users = {}, {}
    for m in comps:
        for d in m.get("deps") or []:
            dep_users.setdefault(d, []).append(m["id"])
        for values in (m.get("optionDeps") or {}).values():
            for deps in (values or {}).values():
                for d in deps or []:
                    opt_users.setdefault(d, [])
                    if m["id"] not in opt_users[d]:
                        opt_users[d].append(m["id"])
    known_vendor = {p["id"] for p in vendor["packages"]}
    for d in sorted(set(dep_users) | set(opt_users)):
        if d not in known_vendor:
            problems.append(f"vendor package '{d}' named by {', '.join(dep_users.get(d, []) + opt_users.get(d, []))} is not in vendor/vendor.json")
    vendor_assets = []
    for p in vendor["packages"]:
        files = [dst for dst in p["files"].values() if dst.endswith((".js", ".css"))]
        if p.get("dest"):
            continue
        entry = {"id": p["id"], "files": files, "license": p["license"], "version": p["version"], "repo": p["repo"], "purpose": p.get("purpose", ""),
                 "preload": p["id"] in dep_users}
        if p["id"] in opt_users and p["id"] not in dep_users:
            entry["onDemand"] = opt_users[p["id"]]
        vendor_assets.append(entry)

    landscape = None
    lp = ROOT / "research" / "catalog.json"
    if lp.exists():
        landscape = load(lp)

    # demo-report thumbnails (node tools/thumbs.cjs); only files that exist are listed
    thumbs, demo = [], None
    tp = ROOT / "gallery" / "thumbs" / "thumbs.json"
    if tp.exists():
        tj = load(tp)
        thumbs = [t for t in tj.get("thumbs", []) if (tp.parent / t.get("file", "")).is_file()]
        demo = {"pages": tj.get("pages"), "report": tj.get("report"), "generated": tj.get("generated")}

    gallery = {
        "version": "0.1.0",
        "categories": cats,
        "components": comps,
        "core": build["core"],
        "styles": build["styles"],
        "themes": build.get("themes", []),
        "vendor": vendor_assets,
        "landscape": landscape,
        "thumbs": thumbs,
        "demo": demo,
        "datasetIndex": {k: {"title": v.get("title", k), "rows": len(v.get("data", [])),
                             "fields": [f["name"] for f in v.get("schema", {}).get("fields", [])]}
                         for k, v in datasets.items()},
    }
    (KIT / "catalog.json").write_text(json.dumps({"categories": cats, "components": comps}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    (ROOT / "gallery").mkdir(exist_ok=True)
    (ROOT / "gallery" / "catalog.js").write_text(js_assign("RK_GALLERY", gallery), encoding="utf-8")
    (ROOT / "gallery" / "samples.js").write_text(js_assign("RK_GALLERY_DATA", datasets), encoding="utf-8")

    # markdown catalogue
    lines = ["# 组件目录 Component catalogue", "",
             f"由 `tools/build_catalog.py` 自动生成 · {len(comps)} components · {len(cats)} categories", ""]
    for c in cats:
        members = [m for m in comps if m.get("category") == c["id"]]
        if not members:
            continue
        lines += [f"## {c['name_zh']} · {c['name']}", "", c.get("desc_zh", ""), "",
                  "| id | 名称 | 引擎 | 能展示什么 | 数据通道 |", "|---|---|---|---|---|"]
        for m in members:
            ch = ", ".join(f"`{k}`{'*' if v.get('required') else ''}" for k, v in (m.get("channels") or {}).items())
            summary = (m.get("summary_zh") or m.get("summary") or "").replace("|", "\\|")
            lines.append(f"| `{m['id']}` | {m.get('name_zh', '')} / {m.get('name', '')} | {m.get('engine', '')} | {summary} | {ch} |")
        lines.append("")
    lines += ["`*` = required channel / 必填通道", ""]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "component-catalog.md").write_text("\n".join(lines), encoding="utf-8")

    live_cats = [c for c in cats if any(m.get("category") == c["id"] for m in comps)]
    print(f"catalog: {len(comps)} components in {len(live_cats)} categories, {len(datasets)} sample datasets, "
          f"{len(vendor_assets)} vendor packages ({sum(1 for v in vendor_assets if v['preload'])} preloaded by the gallery, "
          f"on demand: {', '.join(v['id'] for v in vendor_assets if v.get('onDemand')) or 'none'}), {len(thumbs)} demo thumbnails")
    for p in problems:
        print("  WARN", p)
    return 1 if (args.strict and problems) else 0


if __name__ == "__main__":
    sys.exit(main())
